import assert from 'node:assert/strict';
import {isWithinWeeklyHours,validateWeeklyHours} from '../build/security/weekly-hours.js';
const blank=()=>({enabled:true,days:Array.from({length:7},(_,day)=>({day,enabled:false,slots:Array.from({length:4},()=>({enabled:false,start:'00:00',end:'00:00'}))}))});
const schedule=blank();
schedule.days[0].enabled=true;schedule.days[0].slots[0]={enabled:true,start:'08:00',end:'12:00'};
assert.equal(validateWeeklyHours(schedule),true);
assert.equal(isWithinWeeklyHours(schedule,new Date('2026-10-26T00:59:00Z')),false);
assert.equal(isWithinWeeklyHours(schedule,new Date('2026-10-26T01:00:00Z')),true);
assert.equal(isWithinWeeklyHours(schedule,new Date('2026-10-26T05:00:00Z')),false);
assert.equal(isWithinWeeklyHours(schedule,new Date('2026-10-27T02:00:00Z')),false);
schedule.days[0].slots[1]={enabled:true,start:'12:00',end:'14:00'};assert.equal(validateWeeklyHours(schedule),true);
schedule.days[0].slots[1].start='11:59';assert.equal(validateWeeklyHours(schedule),false);
const night=blank();night.days[6].enabled=true;night.days[6].slots[0]={enabled:true,start:'22:00',end:'02:00'};
assert.equal(validateWeeklyHours(night),true);
assert.equal(isWithinWeeklyHours(night,new Date('2026-10-25T16:00:00Z')),true);
assert.equal(isWithinWeeklyHours(night,new Date('2026-10-25T18:30:00Z')),true);
assert.equal(isWithinWeeklyHours(night,new Date('2026-10-25T19:00:00Z')),false);
night.days[0].enabled=true;night.days[0].slots[0]={enabled:true,start:'01:00',end:'03:00'};
assert.equal(validateWeeklyHours(night),false);
night.enabled=false;assert.equal(isWithinWeeklyHours(night),true);
assert.equal(isWithinWeeklyHours(null),true);
assert.equal(isWithinWeeklyHours(blank()),false);
const invalid=blank();invalid.days[0].slots[0]={enabled:true,start:'24:00',end:'00:00'};assert.equal(validateWeeklyHours(invalid),false);
console.log('PASS: seven-day/four-slot validation, exact boundaries, disabled schedule, closed days, overnight and Sunday-to-Monday overlaps.');
